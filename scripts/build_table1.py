ROOT = Path(__file__).resolve().parents[1]
UNKNOWN = {"", "not-assessed", "unknown", "not-established"}
UNCERTAINTY = {"posterior", "predictive"}


def tokens(value):
    if isinstance(value, list):
        return {str(item).strip() for item in value}
    return {part.strip() for part in str(value or "").split(";")}


def unique_index(items, label):
    result = {}
    for item in items:
        key = item.get("method_id")
        if not key or key in result:
            raise ValueError(f"Missing or duplicate {label} method_id: {key!r}")
        result[key] = item
    return result


def classify(record, row, profile):
    """Return the documented status, without turning an unknown into a negative."""
    field = row["field"]
    if field in UNCERTAINTY:
        assessment = profile.get(field, {})
        status = assessment.get("status", "not-assessed")
        if status not in {"yes", "no", "not-assessed"}:
            raise ValueError(f"Invalid {field} status for {record['method_id']}: {status}")
        return status
    values = tokens(record.get(field))
    if values & UNKNOWN:
        if values - UNKNOWN:
            raise ValueError(f"Mixed known and unknown values: {record['method_id']}/{field}")
        return "not-assessed"
    return "yes" if values.intersection(row["values"]) else "no"


def frequency_band(n, denominator, bands):
    if denominator == 0:
        return None
    percentage = Fraction(100 * n, denominator)
    matches = []
    for band in bands:
        lower = Fraction(str(band["minimum"]))
        if "maximum_exclusive" in band:
            upper_ok = percentage < Fraction(str(band["maximum_exclusive"]))
        else:
            upper_ok = percentage <= Fraction(str(band["maximum_inclusive"]))
        if percentage >= lower and upper_ok:
            matches.append(band["id"])
    if len(matches) != 1:
        raise ValueError(f"Frequency bins do not assign {n}/{denominator} exactly once")
    return matches[0]


def collect_urls(value):
    """Keep source URLs from heterogeneous evidence records without interpreting prose."""
    found = []
    if isinstance(value, dict):
        for item in value.values():
            found.extend(collect_urls(item))
    elif isinstance(value, list):
        for item in value:
            found.extend(collect_urls(item))
    elif isinstance(value, str):
        found.extend(re.findall(r"https?://[^\s;<>\"\[\]{}]+", value))
    return list(dict.fromkeys(url.rstrip(";.,)") for url in found))


def aggregate(records, definition, population, evidence, input_hashes=None):
    by_id = unique_index(records, "atlas")
    profiles = unique_index(evidence.get("profiles", []), "evidence")
    ids = population["method_ids"]
    if not ids or len(ids) != len(set(ids)):
        raise ValueError("Frozen population must contain unique method IDs")
    missing = set(ids) - by_id.keys()
    if missing:
        raise ValueError(f"Frozen methods absent from atlas: {sorted(missing)}")
    block_ids = [block["id"] for block in definition["blocks"]]
    row_ids = [row["id"] for row in definition["rows"]]
    if len(block_ids) != len(set(block_ids)) or len(row_ids) != len(set(row_ids)):
        raise ValueError("Duplicate block or row IDs in table definition")
    block_members = {block: [] for block in block_ids}
    block_membership_unknown = {block: [] for block in block_ids}
    methods = {}
    for method_id in ids:
        record = by_id[method_id]
        blocks = tokens(record.get("methodological_components"))
        if blocks & UNKNOWN or blocks - set(block_ids):
            raise ValueError(f"Invalid/missing building block: {method_id}: {blocks}")
        if "vae" in blocks and "probabilistic" not in blocks:
            raise ValueError(f"VAE must also carry probabilistic membership: {method_id}")
        profile = profiles.get(method_id, {})
        uncertain_membership = profile.get("component_membership_uncertain", {})
        if not isinstance(uncertain_membership, dict):
            raise ValueError(f"Invalid uncertain membership record: {method_id}")
        for block, assessment in uncertain_membership.items():
            if block not in block_ids or not isinstance(assessment, dict) or assessment.get("status") != "not-assessed":
                raise ValueError(f"Invalid uncertain building-block membership: {method_id}/{block}")
            if block in blocks:
                raise ValueError(f"Building-block membership cannot be positive and unknown: {method_id}/{block}")
            block_membership_unknown[block].append(method_id)
        for block in block_ids:
            if block in blocks:
                block_members[block].append(method_id)
        methods[method_id] = {
            "name": record.get("method", method_id),
            "publication_url": record.get("publication_url", ""),
            "resource_url": record.get("resource_url", ""),
            "blocks": [block for block in block_ids if block in blocks],
            "component_membership_uncertain": uncertain_membership,
            "sources": collect_urls([record.get("publication_url"), record.get("resource_url"),
                                     record.get("evidence_sources"), profile]),
            "curation_notes": record.get("curation_notes", ""),
            "reviewed_on": record.get("reviewed_on", ""),
            "profile": profile,
            "axis_values": {row["field"]: record.get(row["field"], "")
                            for row in definition["rows"] if row["field"] not in UNCERTAINTY},
        }
    output_rows = []
    for row in definition["rows"]:
        cells = {}
        for block in block_ids:
            positive, negative, unknown = [], [], []
            for method_id in block_members[block]:
                status = classify(by_id[method_id], row, profiles.get(method_id, {}))
                {"yes": positive, "no": negative, "not-assessed": unknown}[status].append(method_id)
            n, denominator = len(positive), len(positive) + len(negative)
            cells[block] = {
                "n": n, "N": denominator, "unknown": len(unknown),
                "column_total": len(block_members[block]),
                "pct": float(Fraction(100 * n, denominator)) if denominator else None,
                "display_pct": (200 * n + denominator) // (2 * denominator) if denominator else None,
                "band": frequency_band(n, denominator, definition["bands"]),
                "members": positive, "negative_members": negative, "excluded_unknown": unknown,
            }
            assert n <= denominator and denominator + len(unknown) == len(block_members[block])
        output_rows.append({**row, "cells": cells})
    return {
        "version": definition["version"], "date": definition["date"], "title": definition["title"],
        "population": population,
        "input_hashes": input_hashes or {},
        "totals": {"unique_methods": len(ids), "column_memberships": sum(map(len, block_members.values())),
                   "unassessed_column_memberships": sum(map(len, block_membership_unknown.values()))},
        "blocks": [{**block, "total": len(block_members[block["id"]]), "members": block_members[block["id"]],
                    "membership_unknown": len(block_membership_unknown[block["id"]]),
                    "excluded_membership_unknown": block_membership_unknown[block["id"]]}
                   for block in definition["blocks"]],
        "bands": definition["bands"], "rules": definition["rules"],
        "rows": output_rows, "methods": methods,
    }


def make_csv(result):
    output = io.StringIO(newline="")
    fields = ["row_id", "axis", "property", "block_id", "block", "n", "N", "unknown", "column_total",
              "pct", "display_pct", "band", "members", "negative_members", "excluded_unknown"]
    writer = csv.DictWriter(output, fields, lineterminator="\n")
    writer.writeheader()
    for row in result["rows"]:
        for block in result["blocks"]:
            cell = row["cells"][block["id"]]
            values = {**cell, "row_id": row["id"], "axis": row["group"], "property": row["label"],
                      "block_id": block["id"], "block": block["label"]}
            for key in ["members", "negative_members", "excluded_unknown"]:
                values[key] = ";".join(values[key])
            writer.writerow(values)
    return output.getvalue()


