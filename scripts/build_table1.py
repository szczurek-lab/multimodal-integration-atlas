def load_inputs(root):
    paths = {"atlas": root / "data/integration_methods_library.csv",
             "definition": root / "data/table1-definition.json",
             "population": root / "data/table1-population.json",
             "evidence": root / "data/table1-evidence.json"}
    raw = {key: path.read_bytes() for key, path in paths.items()}
    hashes = {str(paths[key].relative_to(root)): hashlib.sha256(value).hexdigest() for key, value in raw.items()}
    records = list(csv.DictReader(io.StringIO(raw["atlas"].decode("utf-8-sig"))))
    documents = {key: json.loads(raw[key]) for key in ["definition", "population", "evidence"]}
    return aggregate(records, documents["definition"], documents["population"], documents["evidence"], hashes)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare output bytes; write nothing")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        result = load_inputs(args.root)
        outputs = {
            "data/table1-counts.json": json.dumps(result, ensure_ascii=False, indent=2) + "\n",
            "data/table1-counts.csv": make_csv(result),
            "table1.html": make_html(result),
        }
        stale = []
        for relative, content in outputs.items():
            path = args.root / relative
            encoded = content.encode("utf-8")
            if args.check:
                if not path.exists() or path.read_bytes() != encoded:
                    stale.append(relative)
            else:
                path.write_bytes(encoded)
        if stale:
            print("Table outputs require regeneration: " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"{'Verified' if args.check else 'Generated'} {len(result['rows'])} × {len(result['blocks'])} cells from {result['totals']['unique_methods']} frozen methods.")
        return 0
    except (OSError, ValueError, KeyError) as error:
        print(f"Table generation failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
